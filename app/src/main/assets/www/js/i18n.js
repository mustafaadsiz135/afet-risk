const n0 = (v, l) => (v == null ? '—' : Math.round(v).toLocaleString(l));
const n1 = (v, l) => (v == null ? '—' : v.toLocaleString(l, { minimumFractionDigits: 1, maximumFractionDigits: 1 }));
const km = (d, l) => (d == null ? '—' : d < 1 ? `${n0(d * 1000, l)} m` : d < 10 ? `${n1(d, l)} km` : `${n0(d, l)} km`);
const m = (d, l) => (d == null ? '—' : d >= 1000 ? `${n1(d / 1000, l)} km` : `${n0(d, l)} m`);
const pct = (p, l) => (p == null ? '—' : p < 0.01 && p > 0 ? (l === 'tr' ? '%1’den az' : 'under 1%') : l === 'tr' ? `%${n0(p * 100, l)}` : `${n0(p * 100, l)}%`);

